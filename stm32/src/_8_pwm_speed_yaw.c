#define ARR 499
#define YAW_CCR_IDLE 85
uint8_t buf[10];
uint8_t speed[4];
uint8_t yaw[4];

void parse_uart(char *buf, char *speed, char *yaw)
{
    char *p = buf;
    uint8_t is_yaw = 0;
    while (*p != '\n' && *p != '\r') {
        if (*p == ' ') {
            p++;
            is_yaw = 1;
        }
        if (!is_yaw) {
            *speed = *p;
            p++;
            speed++;
        } else {
            *yaw = *p;
            yaw++;
            p++;
        }
    }
    *speed = '\0';
    *yaw = '\0';
}

uint8_t string_to_uint8_t(char *buf)
{
    char *p = buf;
    uint8_t tmp = 0;
    while (*p != '\0') {
        tmp = tmp * 10 + (*p - '0');
        p++;
    }
    return tmp;
}

uint16_t clamp(int value, int min, int max)
{
    if (value < min)
        return min;
    if (value > max)
        return max;
    return value;
}

uint16_t speed_to_ccr(uint8_t duty)
{
    uint16_t val = clamp(duty, 0, 100);
    return val * (ARR + 1) / 100;
}

uint16_t yaw_to_ccr(uint8_t yaw_pct)
{
    if (yaw_pct <= 50)
        return (uint16_t)(yaw_pct / 50.0f * YAW_CCR_IDLE);
    else
        return (uint16_t)(85 + (yaw_pct - 50) / 50.0f * 110);
}

void set_motor_a_b(uint16_t ccr_speed, uint16_t ccr_yaw)
{
    int16_t yaw_offset = ccr_yaw - YAW_CCR_IDLE;
    uint16_t ccr_a = clamp(ccr_speed + yaw_offset, 0, ARR + 1);
    uint16_t ccr_b = clamp(ccr_speed - yaw_offset, 0, ARR + 1);

    htim2.Instance->CCR1 = ccr_a;
    htim3.Instance->CCR1 = ccr_b;
}
